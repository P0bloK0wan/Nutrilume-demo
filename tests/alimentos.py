from playwright.sync_api import sync_playwright
R=[];errs=[]
def ok(n,c,d=''): R.append(('PASS' if c else 'FAIL',n,d))
with sync_playwright() as p:
  b=p.chromium.launch(); pg=b.new_context(viewport={'width':1200,'height':900}).new_page()
  pg.on('pageerror',lambda e:errs.append(str(e)))
  pg.add_init_script("document.addEventListener('securitypolicyviolation',e=>{(window.__viol=window.__viol||[]).push(e.violatedDirective)})")
  pg.goto('http://127.0.0.1:8765/index.html'); pg.wait_for_timeout(400)
  pg.click('#v-nut'); pg.click('[data-n=plano]'); pg.wait_for_timeout(300)
  ok('A1 banco aparece',pg.locator('#foodBank').count()==1 and 'BANCO DE ALIMENTOS' in pg.inner_text('#foodBank'))
  pg.fill('#fbQ','ARROZ'); ok('A2 busca ignora maiúscula',pg.locator('#foodBank [data-fb]').count()==2)
  pg.fill('#fbQ','pao'); ok('A3 busca ignora acento (pao→pão)',pg.locator('#foodBank [data-fb]').count()==2)
  pg.fill('#fbQ','<img src=x onerror="window.__x=1">'); pg.wait_for_timeout(100)
  ok('A4 XSS na busca não executa',pg.evaluate("window.__x===undefined && !document.querySelector('#foodBank img[src=x]')"))
  ok('A5 busca sem resultado avisa','Nenhum alimento' in pg.inner_text('#foodBank'))
  pg.fill('#fbQ','frango'); pg.click('#foodBank [data-fb]'); pg.wait_for_timeout(100)
  pg.fill('#fbG','150'); pg.wait_for_timeout(100)
  t=pg.inner_text('#foodBank')
  ok('A6 cálculo 150 g de frango = 239 kcal e 48 g proteína','239' in t and '48 g' in t,t[:300])
  pg.fill('#fbG','99999'); pg.wait_for_timeout(100)
  ok('A7 quantidade limitada a 2000 g',pg.evaluate("bank.g===2000"))
  pg.fill('#fbG','-5'); pg.wait_for_timeout(100)
  ok('A8 quantidade negativa vira mínimo 1',pg.evaluate("bank.g===1"))
  pg.fill('#fbG','150'); n0=pg.locator('#planEd .ed').count(); pg.click('#fbAdd'); pg.wait_for_timeout(200)
  ok('A9 adiciona item na refeição',pg.locator('#planEd .ed').count()==n0+1)
  ok('A10 item guarda macros e porção em g',pg.evaluate("(()=>{const it=draft[edMeal].at(-1);return it[1]==='150 g'&&it[3].k===239})()"))
  ok('A11 total da refeição inclui o item','239' in pg.inner_text('#foodBank'))
  pg.locator('#planEd .ed').last.locator('input[data-f="1"]').fill('1 prato')
  ok('A12 editar a porção à mão remove o cálculo',pg.evaluate("draft[edMeal].at(-1)[3]===undefined") and 'sem cálculo' in pg.inner_text('#foodBank'))
  pg.evaluate("draft[edMeal].push(['x','1',[],{k:'<b>',p:1,c:1,f:1}])"); pg.evaluate("renderBank()")
  ok('A13 macro inválido é ignorado (não vira NaN)',pg.evaluate("!document.querySelector('#foodBank').innerText.includes('NaN')"))
  pg.click('#edPub'); pg.wait_for_timeout(200)
  ok('A14 publicar não quebra',not errs,str(errs))
  ok('A15 sem violação de CSP',pg.evaluate("(window.__viol||[]).length===0"))
  b.close()
f=[r for r in R if r[0]=='FAIL']
for r in R: print(*r)
print({'PASS':len(R)-len(f),'FAIL':len(f)})
